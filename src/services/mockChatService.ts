/**
 * Detect language based on simple Cyrillic/Kazakh specific letters
 */
export function detectLanguage(text: string): SupportedLanguage {
  const kazakhChars = /[әіңғүұқөһӘІҢҒҮҰҚӨҺ]/;
  const kazakhWords = /\b(сәлем|қалай|жақсы|шаршадым|емтихан|керек|жоспар|рахмет|оқу|маған|істеу|қорқамын)\b/i;
  
  if (kazakhChars.test(text) || kazakhWords.test(text)) {
    return 'kk';
  }
  
  // Default check for Cyrillic Russian words
  const russianWords = /\b(привет|как|дела|устал|устала|экзамен|тревога|план|спасибо|учеба|помоги|боюсь|депрессия)\b/i;
  if (russianWords.test(text)) {
    return 'ru';
  }

  // Default to Kazakh for Kyzylorda focus
  return 'kk';
}

